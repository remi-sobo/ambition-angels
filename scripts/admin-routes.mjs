#!/usr/bin/env node
/**
 * The admin route list the middleware 404 check reads (lib/admin/adminRoutes.ts).
 *
 *   node scripts/admin-routes.mjs           print the routes found under app/admin
 *   node scripts/admin-routes.mjs --write   rewrite lib/admin/adminRoutes.generated.ts
 *
 * A route is a page.* or route.* file under app/admin. Private folders (_x)
 * and parallel slots (@x) are skipped, route groups ((x)) drop out of the URL,
 * and the [...not_found] catch-all is left out on purpose: it is what an
 * unknown URL lands on. tests/admin-routes-404.test.ts fails when this list
 * and the filesystem disagree, so a new page cannot ship as a 404.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "lib/admin/adminRoutes.generated.ts");

export function scanAdminRoutes(root = ROOT) {
  const found = new Set();
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (e.name.startsWith("_") || e.name.startsWith("@")) continue;
        walk(p);
      } else if (/^(page|route)\.(tsx|ts|jsx|js)$/.test(e.name)) {
        const rel = path.relative(path.join(root, "app"), path.dirname(p)).split(path.sep);
        const segs = rel.filter((s) => !/^\(.*\)$/.test(s));
        const route = "/" + segs.join("/");
        if (!route.includes("[...not_found]")) found.add(route);
      }
    }
  };
  walk(path.join(root, "app/admin"));
  return [...found].sort();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const routes = scanAdminRoutes();
  if (process.argv.includes("--write")) {
    const body =
      "// GENERATED by scripts/admin-routes.mjs --write. Do not edit by hand.\n" +
      "// Every page and route handler under app/admin, as URL patterns.\n" +
      "export const ADMIN_ROUTES: readonly string[] = [\n" +
      routes.map((r) => `  ${JSON.stringify(r)},\n`).join("") +
      "];\n";
    fs.writeFileSync(OUT, body);
    console.log(`Wrote ${routes.length} routes to ${path.relative(ROOT, OUT)}`);
  } else {
    console.log(routes.join("\n"));
  }
}
